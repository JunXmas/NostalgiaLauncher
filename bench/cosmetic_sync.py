"""Kiểm tra ảnh và đồng bộ danh mục đã duyệt sang backend, không deploy."""

import argparse
import json
import struct
from dataclasses import asdict
from pathlib import Path

from nostalgia.social.cosmetic import load_cosmetic_collection


def verify_artwork(qml_dir: Path) -> None:
    for cosmetic in load_cosmetic_collection().sets:
        if cosmetic.state == "disabled":
            continue
        for art_type in ("frame", "banner"):
            path = qml_dir / "assets" / "cosmetics" / f"{cosmetic.artwork}-{art_type}.png"
            payload = path.read_bytes()
            if payload[:8] != b"\x89PNG\r\n\x1a\n" or len(payload) > 8 * 1024 * 1024:
                raise ValueError(f"Invalid cosmetic PNG: {path}")
            width, height = struct.unpack(">II", payload[16:24])
            if not 1 <= height <= 4096 or width > 4096:
                raise ValueError(f"Cosmetic image too large: {path}")
            if art_type == "frame" and (width != height or payload[25] != 6):
                raise ValueError(f"Frame must be square RGBA: {path}")
            if art_type == "banner" and width != height * 3:
                raise ValueError(f"Banner must have a 3:1 ratio: {path}")


def backend_definition() -> str:
    collection = load_cosmetic_collection()
    document = {
        "schema": 1,
        "revision": collection.revision,
        "items": [asdict(c) for c in collection.sets],
    }
    return (
        "// Generated by NostalgiaLauncher bench/cosmetic_sync.py; do not edit.\n"
        "export const cosmeticCollection = "
        + json.dumps(document, ensure_ascii=False, indent=2)
        + ";\n"
    )


def main() -> None:
    import nostalgia

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--backend", type=Path)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    package_dir = Path(nostalgia.__file__ or "").parent
    verify_artwork(package_dir / "ui" / "qml")
    if arguments.backend:
        path = arguments.backend / "account-service" / "src" / "cosmetic-definition.js"
        expected = backend_definition()
        if arguments.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                raise ValueError("Backend cosmetic definitions are out of sync")
        else:
            if not path.parent.is_dir():
                raise ValueError("Not a Nostalgia backend checkout")
            path.write_text(expected, encoding="utf-8")
    print("Cosmetic definitions and artwork verified; no deployment performed.")


if __name__ == "__main__":
    main()
